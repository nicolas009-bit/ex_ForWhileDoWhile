//WHILE
var num = 1

while (num <= 20) {
    if (num % 2 == 0){
        console.log(num + " É par" + " pt-1");

    }

    num++
}

//DO WHILE

do {
    if (num % 2 == 0) {
        console.log(num + " É par" + " pt-2");

    }
    num++

} while (num <= 20)

//FOR

for (var i = 1; i <= 20; i++) {
    if (i % 2 == 0) {
        console.log(i + " É par" + " pt-3")
    }
}